import { Checkbox, FormField, Input, Label } from "@confia/ui";
import { useId } from "react";
import { useAdminText } from "../../../i18n/use-admin-text.ts";
import type { AdminKey } from "../../../i18n/resources.ts";
import { OptionField, ReadOnlyField, TextField } from "../../organization/components/fields.tsx";
import { ResourceFormDialog, type ResourceFormView } from "../../organization/components/ResourceFormDialog.tsx";
import { CHANNELS, GUARDIAN_CONTROL_IDS, type Guardian, type GuardianField, type GuardianValues } from "../guardian-form.ts";

export interface GuardianFormProps {
  readonly mode: "create" | "edit";
  readonly values: GuardianValues;
  /** Already translated. */
  readonly fieldErrors: Readonly<Partial<Record<GuardianField, string>>>;
  /** The guardian being edited: it only knows whether a document and an RTN are registered, never their digits. */
  readonly row?: Pick<Guardian, "guardianCode" | "hasNationalId" | "hasRtn">;
  readonly form: ResourceFormView;
  readonly onChange: (field: GuardianField, value: string) => void;
  readonly onBlur: (field: GuardianField) => void;
  readonly onClose: () => void;
}

interface WriteOnlyProps {
  readonly kind: "nationalId" | "rtn";
  readonly has: boolean;
  readonly values: GuardianValues;
  readonly fieldErrors: GuardianFormProps["fieldErrors"];
  readonly onChange: GuardianFormProps["onChange"];
  readonly onBlur: GuardianFormProps["onBlur"];
}

const WRITE_ONLY_KEYS: Readonly<
  Record<WriteOnlyProps["kind"], { current: AdminKey; replace: AdminKey; replaceHelp: AdminKey; remove: AdminKey; removeHelp: AdminKey; removeField: GuardianField }>
> = {
  nationalId: {
    current: "guardians.currentDocument",
    replace: "guardians.replaceDocument",
    replaceHelp: "guardians.replaceDocumentHelp",
    remove: "guardians.removeDocument",
    removeHelp: "guardians.removeDocumentHelp",
    removeField: "removeNationalId",
  },
  rtn: {
    current: "guardians.currentRtn",
    replace: "guardians.replaceRtn",
    replaceHelp: "guardians.replaceRtnHelp",
    remove: "guardians.removeRtn",
    removeHelp: "guardians.removeRtnHelp",
    removeField: "removeRtn",
  },
};

/**
 * A value that is only ever written (the national id, the RTN), when editing, in three separate acts so none happens by
 * accident: whether there is one is shown and cannot be edited, a separate box replaces it (empty keeps it), and only an
 * explicit checkbox removes it. The box never gets the stored value.
 */
function WriteOnlyValue({ kind, has, values, fieldErrors, onChange, onBlur }: WriteOnlyProps) {
  const { t } = useAdminText();
  const helpId = useId();
  const keys = WRITE_ONLY_KEYS[kind];
  const removing = values[keys.removeField] === "true";
  const removeId = GUARDIAN_CONTROL_IDS[keys.removeField];

  return (
    <>
      <FormField label={t(keys.current)} controlId={`${GUARDIAN_CONTROL_IDS[kind]}-current`}>
        {(control) => <Input {...control} readOnly value={t(has ? "guardians.registered" : "guardians.noneText")} />}
      </FormField>
      <TextField
        label={t(keys.replace)}
        description={t(keys.replaceHelp)}
        controlId={GUARDIAN_CONTROL_IDS[kind]}
        value={values[kind]}
        error={fieldErrors[kind]}
        disabled={removing}
        sensitive
        onChange={(value) => {
          onChange(kind, value);
        }}
        onBlur={() => {
          onBlur(kind);
        }}
      />
      {has ? (
        <div className="flex flex-col gap-1.5">
          <div className="flex items-center gap-2">
            <Checkbox
              id={removeId}
              aria-describedby={helpId}
              checked={removing}
              onCheckedChange={(checked) => {
                onChange(keys.removeField, checked === true ? "true" : "false");
                // What was typed to replace the value is dropped: removing and replacing are different acts.
                if (checked === true) onChange(kind, "");
              }}
            />
            <Label htmlFor={removeId}>{t(keys.remove)}</Label>
          </div>
          <p id={helpId} className="text-sm text-text-secondary">
            {t(keys.removeHelp)}
          </p>
        </div>
      ) : null}
    </>
  );
}

/**
 * The form of a guardian, in a dialog. The code is generated by the system (shown, fixed, once the guardian exists). The
 * national id and the RTN are write-only: a new guardian types them, an existing one only shows whether they exist.
 * Everything personal is marked sensitive, so the browser does not spell-check, autocorrect or autofill it.
 */
export function GuardianForm({ mode, values, fieldErrors, row, form, onChange, onBlur, onClose }: GuardianFormProps) {
  const { t } = useAdminText();
  const editing = mode === "edit";
  const text = (field: GuardianField) => ({
    controlId: GUARDIAN_CONTROL_IDS[field],
    value: values[field],
    error: fieldErrors[field],
    onChange: (value: string) => {
      onChange(field, value);
    },
    onBlur: () => {
      onBlur(field);
    },
  });

  return (
    <ResourceFormDialog
      title={t(editing ? "guardians.editTitle" : "guardians.createTitle")}
      description={t(editing ? "guardians.editDescription" : "guardians.createDescription")}
      submitLabel={t("organization.common.save")}
      form={form}
      onClose={onClose}
    >
      {editing ? <ReadOnlyField label={t("guardians.fields.code")} controlId="guardian-code" value={row?.guardianCode ?? ""} /> : null}
      <TextField label={t("guardians.fields.firstName")} required sensitive {...text("firstName")} />
      <TextField label={t("guardians.fields.lastName")} required sensitive {...text("lastName")} />
      {editing ? (
        <>
          <WriteOnlyValue kind="nationalId" has={row?.hasNationalId === true} values={values} fieldErrors={fieldErrors} onChange={onChange} onBlur={onBlur} />
          <WriteOnlyValue kind="rtn" has={row?.hasRtn === true} values={values} fieldErrors={fieldErrors} onChange={onChange} onBlur={onBlur} />
        </>
      ) : (
        <>
          <TextField label={t("guardians.fields.nationalId")} description={t("guardians.nationalIdHelp")} sensitive {...text("nationalId")} />
          <TextField label={t("guardians.fields.rtn")} description={t("guardians.rtnHelp")} sensitive {...text("rtn")} />
        </>
      )}
      <TextField label={t("guardians.fields.email")} sensitive {...text("email")} />
      <TextField label={t("guardians.fields.phone")} sensitive {...text("phone")} />
      <TextField label={t("guardians.fields.address")} sensitive {...text("address")} />
      <OptionField
        label={t("guardians.fields.preferredChannel")}
        options={CHANNELS.map((channel) => ({ value: channel, label: t(`guardians.channel.${channel}`) }))}
        {...text("preferredChannel")}
      />
      {editing ? (
        <OptionField
          label={t("guardians.fields.status")}
          options={[
            { value: "ACTIVE", label: t("organization.common.active") },
            { value: "INACTIVE", label: t("organization.common.inactive") },
          ]}
          {...text("status")}
        />
      ) : null}
    </ResourceFormDialog>
  );
}
