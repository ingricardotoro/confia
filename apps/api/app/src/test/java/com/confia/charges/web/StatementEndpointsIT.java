    @Test
    void anAdministratorReadsTheStatementWithMoneyAsStringsTheChargeOfEachLineAndTheRunningBalance() throws SQLException {
        Member admin = member(StaffRole.ADMINISTRATOR.code());
        Seeded seeded = seedAndAccrue(admin);

        HttpResponse<String> response = get(path(seeded.charged(), "from=2027-02-01&to=2027-04-30"), admin);

        assertThat(response.statusCode()).as(response.body()).isEqualTo(200);
        JsonNode body = HarnessProcess.json(response);
        assertThat(body.propertyNames()).containsExactly("studentId", "studentCode", "firstName", "lastName", "from", "to",
                "sections");
        assertThat(body.get("from").asString()).isEqualTo("2027-02-01");
        assertThat(body.get("to").asString()).isEqualTo("2027-04-30");
        assertThat(body.get("sections")).hasSize(1);
        JsonNode section = body.get("sections").get(0);
        assertThat(section.propertyNames()).containsExactly("currency", "openingBalance", "closingBalance", "totalLines",
                "page", "size", "lines");
        assertThat(section.get("currency").asString()).isEqualTo("HNL");
        assertThat(section.get("openingBalance").get("amount").asString()).isEqualTo("0.00");
        assertThat(section.get("openingBalance").get("currency").asString()).isEqualTo("HNL");
        assertThat(section.get("closingBalance").get("amount").asString()).isEqualTo("3300.00");
        assertThat(section.get("closingBalance").get("amount").isString()).isTrue();
        assertThat(section.get("totalLines").asLong()).isEqualTo(2);
        JsonNode first = section.get("lines").get(0);
        assertThat(first.propertyNames()).containsExactly("transactionId", "kind", "effectiveOn", "postedAt", "lineNumber",
                "reason", "reversesTransactionId", "debit", "credit", "balance", "charge");
        assertThat(first.get("kind").asString()).isEqualTo("CHARGE");
        assertThat(first.get("debit").get("amount").asString()).isEqualTo("1650.00");
        assertThat(first.get("credit").get("amount").asString()).isEqualTo("0.00");
        assertThat(first.get("balance").get("amount").asString()).isEqualTo("1650.00");
        assertThat(section.get("lines").get(1).get("balance").get("amount").asString()).isEqualTo("3300.00");
        JsonNode charge = first.get("charge");
        assertThat(charge.get("conceptCode").asString()).isEqualTo("COL");
        assertThat(charge.get("conceptName").asString()).isEqualTo("Colegiatura");
        assertThat(charge.get("periodLabel").asString()).isEqualTo("2027-02");
        assertThat(charge.get("dueOn").asString()).isEqualTo("2027-02-05");
    }

    @Test
    void pagesAndTheCurrencyFilterApplyToTheLinesOfEachSection() throws SQLException {
        Member admin = member(StaffRole.ADMINISTRATOR.code());
        Seeded seeded = seedAndAccrue(admin);

        JsonNode second = HarnessProcess.json(get(path(seeded.charged(), "from=2027-02-01&to=2027-04-30&size=1&page=1"),
                admin)).get("sections").get(0);
        assertThat(second.get("totalLines").asLong()).isEqualTo(2);
        assertThat(second.get("page").asInt()).isEqualTo(1);
        assertThat(second.get("lines")).hasSize(1);
        assertThat(second.get("lines").get(0).get("balance").get("amount").asString()).isEqualTo("3300.00");

        JsonNode usd = HarnessProcess.json(get(path(seeded.charged(), "currency=USD&from=2027-02-01&to=2027-04-30"), admin));
        assertThat(usd.get("sections")).hasSize(1);
        assertThat(usd.get("sections").get(0).get("currency").asString()).isEqualTo("USD");
        assertThat(usd.get("sections").get(0).get("closingBalance").get("amount").asString()).isEqualTo("0.00");
        assertThat(usd.get("sections").get(0).get("lines")).isEmpty();
    }

    @Test
    void aStudentWithoutAccountHasNoSectionsAndTheDefaultPeriodIsAccepted() throws SQLException {
        Member admin = member(StaffRole.ADMINISTRATOR.code());
        Seeded seeded = seedAndAccrue(admin);

        JsonNode body = HarnessProcess.json(get(path(seeded.empty(), ""), admin));

        assertThat(body.get("sections")).isEmpty();
        assertThat(body.get("studentCode").asString()).startsWith("E-");
        assertThat(LocalDate.parse(body.get("from").asString())).isEqualTo(LocalDate.parse(body.get("to").asString())
                .minusMonths(12));
    }

    @Test
    void aRoleThatReadsChargesReadsTheStatementAndAnUnauthenticatedCallerIsRefused() throws SQLException {
        Member admin = member(StaffRole.ADMINISTRATOR.code());
        Seeded seeded = seedAndAccrue(admin);
        Member cashier = sameInstitution(admin.institution(), StaffRole.CASHIER.code());

        assertThat(get(path(seeded.charged(), "from=2027-02-01&to=2027-04-30"), cashier).statusCode()).isEqualTo(200);
        assertThat(send("GET", path(seeded.charged(), ""), null).statusCode()).isEqualTo(401);
        assertThat(send("GET", path(seeded.charged(), ""), "not-a-token").statusCode()).isEqualTo(401);
    }

    @Test
    void invalidParametersAreRefusedWithValidationFailedAndLeaveNoAuditEntry() throws SQLException {
        Member admin = member(StaffRole.ADMINISTRATOR.code());
        Seeded seeded = seedAndAccrue(admin);

        for (String query : List.of("from=2027-04-30&to=2027-02-01", "from=2027-02-30", "from=yesterday", "currency=EUR",
                "currency=hnl", "size=0", "size=101", "page=-1", "page=abc")) {
            assertProblem(get(path(seeded.charged(), query), admin), 400, "validation-failed");
        }
        assertThat(auditCount(admin.institution())).isZero();
    }

    @Test
    void aStudentOfAnotherInstitutionOrUnknownIsNotFoundAndNothingLeaks() throws SQLException {
        Member mine = member(StaffRole.ADMINISTRATOR.code());
        Seeded seeded = seedAndAccrue(mine);
        Member theirs = member(StaffRole.ADMINISTRATOR.code());
        seedAndAccrue(theirs);

        HttpResponse<String> foreign = get(path(seeded.charged(), "from=2027-02-01&to=2027-04-30"), theirs);
        assertProblem(foreign, 404, "resource-not-found");
        assertThat(foreign.body()).doesNotContain("1650").doesNotContain("Colegiatura");
        assertProblem(get(path(UUID.randomUUID(), ""), mine), 404, "resource-not-found");
        assertProblem(get(STUDENTS + "not-a-uuid/statement", mine), 400, "validation-failed");
        assertThat(auditCount(theirs.institution())).isZero();
    }

    @Test
    void everyAcceptedReadIsAuditedWithTheActorAndTheStudentAndNoAmount() throws SQLException {
        Member admin = member(StaffRole.ADMINISTRATOR.code());
        Seeded seeded = seedAndAccrue(admin);

        get(path(seeded.charged(), "from=2027-02-01&to=2027-04-30"), admin);
        get(path(seeded.empty(), "from=2027-02-01&to=2027-04-30"), admin);

        assertThat(auditCount(admin.institution())).isEqualTo(2);
        try (Connection c = StaffRoleFixtures.ownerTransaction(admin.institution());
                PreparedStatement s = c.prepareStatement("select count(*) from shared_audit_log where institution_id = ? "
                        + "and action = 'charges.statement.viewed' and actor_id = ? and entity_id = ? "
                        + "and after_value::text not like '%1650%'")) {
            s.setObject(1, admin.institution());
            s.setObject(2, admin.account());
            s.setString(3, seeded.charged().toString());
            try (var rs = s.executeQuery()) {
                rs.next();
                assertThat(rs.getLong(1)).isEqualTo(1);
            }
        }
    }

