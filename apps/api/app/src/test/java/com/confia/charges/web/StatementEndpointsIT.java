/**
 * The statement route on the real administrative process, started through the production launcher against a real
 * PostgreSQL with the least-privilege role of the application (docs/cortes/ledger-account-statement.md): the shape of the
 * answer, the money as strings, the pages, the filters, the validation, the {@code 404} of a student of another
 * institution, the audit entry of each read and the credential. The charges are generated by the real accrual engine, run
 * by the test as the worker would. Every token is made by the production issuer; every institution is seeded as the owner.
 */
