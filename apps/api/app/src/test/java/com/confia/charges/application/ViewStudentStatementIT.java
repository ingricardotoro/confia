    @Test
    void twelveMonthlyChargesOfTheEngineReconstructTheBalanceFromZeroAndEachLineNamesItsCharge() throws SQLException {
        Env env = seed(2);
        accrueTwelveMonths(env);
        UUID student = env.students().get(0);
        LocalDate to = LocalDate.parse("2028-01-31");

        StatementView view = statements().view(env.actor(), UUID.randomUUID().toString(), student, null, FIRST_PERIOD, to,
                0, 100);

        assertThat(view.sections()).hasSize(1);
        StatementView.Section section = view.sections().get(0);
        assertThat(section.currency()).isEqualTo(CurrencyCode.HNL);
        assertThat(section.totalLines()).isEqualTo(12);
        assertThat(section.openingBalance()).isEqualTo(hnl("0"));
        // Debits minus credits of the sub-account, summed by the test straight from the entries: 12 x 1,650.00.
        assertThat(ledgerBalance(env, student, "HNL")).isEqualByComparingTo("19800.00");
        assertThat(section.closingBalance().amount()).isEqualByComparingTo(ledgerBalance(env, student, "HNL"));
        assertThat(section.closingBalance()).isEqualTo(new LedgerQueries(transactionRunner(),
                new JooqLedgerRepository(dsl)).balanceOf(env.ledgerActor(), student, CurrencyCode.HNL, to, null));
        for (int i = 0; i < 12; i++) {
            StatementView.Line line = section.lines().get(i);
            LocalDate month = FIRST_PERIOD.plusMonths(i);
            assertThat(line.kind()).isEqualTo("CHARGE");
            assertThat(line.debit()).isEqualTo(hnl("1650.00"));
            assertThat(line.credit()).isEqualTo(hnl("0"));
            assertThat(line.balance()).as("running balance of line %d", i).isEqualTo(hnl(String.valueOf(1650 * (i + 1))));
            assertThat(line.charge()).isNotNull();
            assertThat(line.charge().conceptCode()).isEqualTo("COL");
            assertThat(line.charge().conceptName()).isEqualTo("Colegiatura");
            assertThat(line.charge().conceptCategory()).isEqualTo("TUITION");
            assertThat(line.charge().periodLabel()).isEqualTo(month.toString().substring(0, 7));
            assertThat(line.charge().periodStart()).isEqualTo(month);
            assertThat(line.charge().dueOn()).isEqualTo(month.withDayOfMonth(5));
            assertThat(line.charge().origin()).isEqualTo("AUTOMATIC");
        }
        // The other student of the institution has its own, identical, statement and the first one never saw it.
        StatementView other = statements().view(env.actor(), UUID.randomUUID().toString(), env.students().get(1), null,
                FIRST_PERIOD, to, 0, 100);
        assertThat(other.sections().get(0).closingBalance()).isEqualTo(hnl("19800.00"));
        assertThat(other.sections().get(0).lines()).extracting(StatementView.Line::transactionId)
                .doesNotContainAnyElementsOf(section.lines().stream().map(StatementView.Line::transactionId).toList());
    }

    @Test
    void theDefaultPeriodIsTheLastTwelveMonthsAndItsOpeningBalanceIsEverythingBefore() throws SQLException {
        Env env = seed(1);
        accrueTwelveMonths(env);

        // The fixed clock is 2028-03-01 in Honduras: the period is 2027-03-01 to 2028-03-01, so February is the opening.
        StatementView view = statements().view(env.actor(), UUID.randomUUID().toString(), env.students().get(0), null,
                null, null, 0, 50);

        assertThat(view.from()).isEqualTo(LocalDate.parse("2027-03-01"));
        assertThat(view.to()).isEqualTo(LocalDate.parse("2028-03-01"));
        StatementView.Section section = view.sections().get(0);
        assertThat(section.openingBalance()).isEqualTo(hnl("1650.00"));
        assertThat(section.totalLines()).isEqualTo(11);
        assertThat(section.lines().get(0).balance()).isEqualTo(hnl("3300.00"));
        assertThat(section.closingBalance()).isEqualTo(hnl("19800.00"));
    }

    @Test
    void aReversedChargeAndAPaymentAreLinesWithoutAChargeAndTheBalanceNetsOut() throws SQLException {
        Env env = seed(1);
        accrueTwelveMonths(env);
        UUID student = env.students().get(0);
        UUID march = statements().view(env.actor(), UUID.randomUUID().toString(), student, null, FIRST_PERIOD,
                LocalDate.parse("2028-01-31"), 0, 100).sections().get(0).lines().get(1).transactionId();
        posting().reverse(env.ledgerActor(), new LedgerPosting.ReverseCommand(march, "charges",
                LocalDate.parse("2027-03-20"), REASON, "charges:void:" + march));
        posting().post(env.ledgerActor(), new LedgerPosting.PostCommand(TransactionKind.PAYMENT,
                LocalDate.parse("2027-02-10"), "payments", null, null, "payment:1",
                List.of(new LedgerEntry(env.cash(), null, EntrySide.DEBIT, hnl("500.00")),
                        new LedgerEntry(env.receivable(), student, EntrySide.CREDIT, hnl("500.00")))));

        StatementView.Section section = statements().view(env.actor(), UUID.randomUUID().toString(), student, null,
                FIRST_PERIOD, LocalDate.parse("2028-01-31"), 0, 100).sections().get(0);

        assertThat(section.totalLines()).isEqualTo(14);
        List<StatementView.Line> withoutCharge = section.lines().stream().filter(line -> line.charge() == null).toList();
        assertThat(withoutCharge).extracting(StatementView.Line::kind).containsExactlyInAnyOrder("REVERSAL", "PAYMENT");
        StatementView.Line reversal = withoutCharge.stream().filter(line -> line.kind().equals("REVERSAL")).findFirst()
                .orElseThrow();
        assertThat(reversal.reason()).isEqualTo(REASON);
        assertThat(reversal.reversesTransactionId()).isEqualTo(march);
        assertThat(reversal.credit()).isEqualTo(hnl("1650.00"));
        StatementView.Line payment = withoutCharge.stream().filter(line -> line.kind().equals("PAYMENT")).findFirst()
                .orElseThrow();
        assertThat(payment.credit()).isEqualTo(hnl("500.00"));
        // The charge and its reversal net to zero: 19,800.00 - 1,650.00 - 500.00.
        assertThat(section.closingBalance()).isEqualTo(hnl("17650.00"));
        assertThat(section.closingBalance().amount()).isEqualByComparingTo(ledgerBalance(env, student, "HNL"));
        assertThat(section.lines().get(section.lines().size() - 1).balance()).isEqualTo(section.closingBalance());
    }

    @Test
    void twoCurrenciesAreTwoSectionsAndAskingForOneReturnsOnlyIt() throws SQLException {
        Env env = seed(1);
        UUID student = env.students().get(0);
        posting().post(env.ledgerActor(), new LedgerPosting.PostCommand(TransactionKind.CHARGE,
                LocalDate.parse("2027-02-01"), "charges", null, null, "usd:1",
                List.of(new LedgerEntry(env.receivable(), student, EntrySide.DEBIT, Money.of("20.00", CurrencyCode.USD)),
                        new LedgerEntry(env.cash(), null, EntrySide.CREDIT, Money.of("20.00", CurrencyCode.USD)))));
        accrueTwelveMonths(env);

        StatementView both = statements().view(env.actor(), UUID.randomUUID().toString(), student, null, FIRST_PERIOD,
                LocalDate.parse("2028-01-31"), 0, 100);
        assertThat(both.sections()).extracting(StatementView.Section::currency)
                .containsExactly(CurrencyCode.HNL, CurrencyCode.USD);
        assertThat(both.sections().get(1).closingBalance()).isEqualTo(Money.of("20.00", CurrencyCode.USD));
        assertThat(both.sections().get(1).lines().get(0).charge()).isNull();

        StatementView onlyUsd = statements().view(env.actor(), UUID.randomUUID().toString(), student, CurrencyCode.USD,
                FIRST_PERIOD, LocalDate.parse("2028-01-31"), 0, 100);
        assertThat(onlyUsd.sections()).hasSize(1);
        assertThat(onlyUsd.sections().get(0).currency()).isEqualTo(CurrencyCode.USD);
    }

    @Test
    void aStudentWithNoAccountHasAnEmptyStatementAndStillLeavesTheAuditEntry() throws SQLException {
        Env env = seed(1);

        StatementView view = statements().view(env.actor(), UUID.randomUUID().toString(), env.students().get(0), null,
                null, null, 0, 50);
        assertThat(view.sections()).isEmpty();
        StatementView zero = statements().view(env.actor(), UUID.randomUUID().toString(), env.students().get(0),
                CurrencyCode.HNL, null, null, 0, 50);
        assertThat(zero.sections().get(0).closingBalance()).isEqualTo(hnl("0"));
        assertThat(zero.sections().get(0).lines()).isEmpty();
        assertThat(auditCount(env)).isEqualTo(2);
    }

    @Test
    void aStudentOfAnotherInstitutionIsNotFoundAndNothingOfItLeaks() throws SQLException {
        Env env = seed(1);
        Env stranger = seed(1);
        accrueTwelveMonths(stranger);

        assertThatThrownBy(() -> statements().view(env.actor(), UUID.randomUUID().toString(), stranger.students().get(0),
                null, FIRST_PERIOD, LocalDate.parse("2028-01-31"), 0, 100)).isInstanceOf(ResourceNotFoundException.class);
        assertThatThrownBy(() -> statements().view(env.actor(), UUID.randomUUID().toString(), UUID.randomUUID(), null,
                null, null, 0, 100)).isInstanceOf(ResourceNotFoundException.class);
        assertThat(auditCount(env)).isZero();
        assertThat(auditCount(stranger)).isZero();
    }

    @Test
    void everyReadLeavesOneAuditEntryOfTheActorWithTheFiltersAndNoAmountOrName() throws SQLException {
        Env env = seed(1);
        accrueTwelveMonths(env);
        UUID student = env.students().get(0);
        UUID request = UUID.randomUUID();

        statements().view(env.actor(), request.toString(), student, CurrencyCode.HNL, FIRST_PERIOD,
                LocalDate.parse("2028-01-31"), 0, 100);

        try (Connection c = StaffRoleFixtures.ownerTransaction(env.institution());
                PreparedStatement s = c.prepareStatement("select actor_id, entity_type, entity_id, outcome, "
                        + "after_value::text, request_id from shared_audit_log where institution_id = ? and "
                        + "action = 'charges.statement.viewed'")) {
            s.setObject(1, env.institution());
            try (ResultSet rs = s.executeQuery()) {
                assertThat(rs.next()).isTrue();
                assertThat(rs.getObject(1, UUID.class)).isEqualTo(env.admin());
                assertThat(rs.getString(2)).isEqualTo("charges.statement");
                assertThat(rs.getString(3)).isEqualTo(student.toString());
                assertThat(rs.getString(4)).isEqualTo("success");
                assertThat(rs.getString(5)).contains("HNL", "2027-02-01", "2028-01-31").doesNotContain("1650")
                        .doesNotContain("Ana").doesNotContain("Prueba");
                assertThat(rs.getObject(6, UUID.class)).isEqualTo(request);
                assertThat(rs.next()).isFalse();
            }
        }
    }
