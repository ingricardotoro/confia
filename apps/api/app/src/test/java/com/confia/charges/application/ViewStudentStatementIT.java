    /** Accrues the twelve monthly periods through the real engine, one run per period. */
    private void accrueTwelveMonths(Env env) {
        for (int month = 0; month < 12; month++) {
            LocalDate period = FIRST_PERIOD.plusMonths(month);
            var run = manage().request(env.actor(), UUID.randomUUID().toString(), "key-" + period, env.plan(), period,
                    null);
            execution().execute(env.system(), run.id());
        }
    }

    private BigDecimal ledgerBalance(Env env, UUID student, String currency) throws SQLException {
        return decimal(env.institution(), "select coalesce(sum(case e.side when 'DEBIT' then e.amount else -e.amount end), 0) "
                + "from ledger_entry e join ledger_student_account a on a.institution_id = e.institution_id and "
                + "a.id = e.student_account_id where e.institution_id = ? and a.student_id = ? and a.currency = ?",
                env.institution(), student, currency);
    }

    private long auditCount(Env env) throws SQLException {
        return decimal(env.institution(), "select count(*) from shared_audit_log where institution_id = ? and "
                + "action = 'charges.statement.viewed'", env.institution()).longValue();
    }

