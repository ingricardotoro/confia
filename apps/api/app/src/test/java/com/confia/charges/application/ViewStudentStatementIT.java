    private static final Clock CLOCK = Clock.fixed(Instant.parse("2028-03-01T18:00:00Z"), ZoneOffset.UTC);
    private static final LocalDate FIRST_PERIOD = LocalDate.parse("2027-02-01");
    private static final String REASON = "charged twice by mistake in the run";

