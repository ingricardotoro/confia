-- Thirty-seventh migration (F2 deliverables 4, 5 and 7, scholarships cut 1, second task; docs/cortes/scholarships-awards.md). The
-- accrual engine applies the approved awards of V36 to the charges it generates from now on. This migration only ADDS to the
-- charges: no existing charge row is touched (the table is insert-only and the new columns are either generated from the columns
-- that were always there or empty for every charge that was issued without a scholarship).
--
-- WHAT A CHARGE KEEPS (the discount, its currency, the tax and the total exist since V32; the discount IS the benefit):
--   * the award that produced the benefit and the code of its scholarship, copied at accrual time (a later edit of the
--     scholarship never changes the charge);
--   * the net base, which is the gross base minus the benefit, generated by the database so it can never disagree with them.
--
-- THE DATABASE REFUSES, to every role including the owner:
--   * a charge with an award and no benefit, or with a benefit and no award, or with the code of another scholarship (INV-16);
--   * a charge whose award is not approved at the moment the charge is written, belongs to another student, does not cover the
--     date of the charge (the pricing date, the first day of the period, both ends included), belongs to an inactive scholarship,
--     does not cover the payment concept of the charge, is in another currency, or whose benefit is not exactly the share or the
--     fixed amount of its scholarship, limited to its cap per period and to the base (INV-15, the same rule the engine applies:
--     round(numeric, 2) rounds the midpoint away from zero, HALF_UP for positive amounts);
--   * a charge whose ledger transaction does not carry, besides the debit of the student sub-account for the total, exactly one
--     other debit, for the benefit, when there is one, and no other debit when there is none.
--
-- A benefit may leave nothing to pay (a scholarship of 100 %, or a fixed amount that reaches the base): the total of a charge is
-- then zero, and the ledger transaction has no entry on the student sub-account because the ledger refuses an entry of zero. The
-- charge still exists, with its base, its benefit and its award. The void of such a charge has no credit on the sub-account either.
--
-- The map of posting accounts gains the purpose BENEFITS: the account that receives the debit of the benefit. The accountant has not
-- validated it yet (assumption S4 of the cut): it accepts an account of type INCOME (contra-revenue) or EXPENSE.

ALTER TABLE charges_charge
    ADD COLUMN scholarship_award_id UUID,
    ADD COLUMN scholarship_code     VARCHAR(30),
    ADD COLUMN net_base_amount      NUMERIC(14,4) GENERATED ALWAYS AS (base_amount - discount_amount) STORED,
    ADD COLUMN net_base_currency    CHAR(3)       GENERATED ALWAYS AS (base_currency) STORED;

ALTER TABLE charges_charge
    ADD CONSTRAINT charges_charge_award_fk FOREIGN KEY (institution_id, scholarship_award_id)
        REFERENCES scholarships_award (institution_id, id),
    ADD CONSTRAINT charges_charge_benefit_chk CHECK (
        (scholarship_award_id IS NULL AND scholarship_code IS NULL AND discount_amount = 0)
        OR (scholarship_award_id IS NOT NULL AND scholarship_code IS NOT NULL AND discount_amount > 0));

CREATE INDEX charges_charge_award_idx ON charges_charge (institution_id, scholarship_award_id)
    WHERE scholarship_award_id IS NOT NULL;

-- INV-08, INV-09, INV-10 as before, except that the total may be zero when the benefit takes the whole base.
ALTER TABLE charges_charge DROP CONSTRAINT charges_charge_amounts_chk;
ALTER TABLE charges_charge ADD CONSTRAINT charges_charge_amounts_chk CHECK (base_amount > 0 AND discount_amount >= 0
    AND tax_amount >= 0 AND discount_amount <= base_amount AND total_amount >= 0
    AND total_amount = base_amount - discount_amount + tax_amount);

ALTER TABLE charges_posting_account DROP CONSTRAINT charges_posting_account_purpose_chk;
ALTER TABLE charges_posting_account ADD CONSTRAINT charges_posting_account_purpose_chk
    CHECK (purpose IN ('RECEIVABLE', 'REVENUE', 'TAX_PAYABLE', 'BENEFITS'));

CREATE OR REPLACE FUNCTION charges_charge_before_insert() RETURNS trigger
    LANGUAGE plpgsql
    SECURITY INVOKER
    SET search_path = pg_catalog, public
AS $$
DECLARE
    price         catalog_price_list_item%ROWTYPE;
    tax_period    catalog_tax_rate_period%ROWTYPE;
    posting       ledger_transaction%ROWTYPE;
    award         RECORD;
    expected      numeric;
    debit_count   integer;
    debit_total   numeric;
    debit_ccy     text;
    all_debits    integer;
    all_total     numeric;
    other_debits  integer;
    expected_other integer;
BEGIN
    IF NEW.origin = 'AUTOMATIC' THEN
        SELECT * INTO price FROM catalog_price_list_item
            WHERE institution_id = NEW.institution_id AND id = NEW.price_list_item_id;
        IF NOT FOUND
                OR price.payment_concept_id <> NEW.payment_concept_id
                OR price.amount <> NEW.base_amount
                OR price.currency <> NEW.base_currency
                OR price.valid_from > NEW.pricing_date
                OR (price.valid_to IS NOT NULL AND price.valid_to < NEW.pricing_date) THEN
            RAISE EXCEPTION 'an automatic charge references the price in force at its pricing date, which is its base'
                USING ERRCODE = 'check_violation';
        END IF;
    END IF;

    IF NEW.is_taxable THEN
        SELECT * INTO tax_period FROM catalog_tax_rate_period
            WHERE institution_id = NEW.institution_id AND id = NEW.tax_rate_period_id;
        IF NOT FOUND
                OR tax_period.tax_rate_id <> NEW.tax_rate_id
                OR tax_period.rate_percent <> NEW.tax_rate_percent
                OR tax_period.valid_from > NEW.pricing_date
                OR (tax_period.valid_to IS NOT NULL AND tax_period.valid_to < NEW.pricing_date) THEN
            RAISE EXCEPTION 'a taxable charge references the tax rate in force at its pricing date'
                USING ERRCODE = 'check_violation';
        END IF;
    END IF;

    -- INV-15, INV-16: the benefit of a charge is the benefit of an award that is approved now, of this student, in force at the
    -- pricing date, of an active scholarship that covers the concept, in the currency of the charge.
    IF NEW.scholarship_award_id IS NOT NULL THEN
        SELECT a.status, a.student_id, a.valid_from, a.valid_to, s.id AS scholarship_id, s.code, s.is_active, s.benefit_type,
               s.percent, s.fixed_amount, s.period_cap, s.currency
          INTO award
          FROM scholarships_award a
          JOIN scholarships_scholarship s ON s.institution_id = a.institution_id AND s.id = a.scholarship_id
         WHERE a.institution_id = NEW.institution_id AND a.id = NEW.scholarship_award_id;
        IF NOT FOUND
                OR NEW.origin <> 'AUTOMATIC'
                OR award.status <> 'approved'
                OR award.student_id <> NEW.student_id
                OR NEW.pricing_date < award.valid_from
                OR NEW.pricing_date > award.valid_to
                OR NOT award.is_active
                OR award.code <> NEW.scholarship_code
                OR award.currency <> NEW.base_currency
                OR NOT EXISTS (SELECT 1 FROM scholarships_scholarship_concept c
                                WHERE c.institution_id = NEW.institution_id AND c.scholarship_id = award.scholarship_id
                                  AND c.payment_concept_id = NEW.payment_concept_id) THEN
            RAISE EXCEPTION 'a charge applies an approved award of the student, in force at its pricing date, that covers its concept'
                USING ERRCODE = 'check_violation';
        END IF;
        IF award.benefit_type = 'PERCENTAGE' THEN
            expected := round(NEW.base_amount * award.percent / 100, 2);
        ELSE
            expected := award.fixed_amount;
        END IF;
        expected := LEAST(expected, COALESCE(award.period_cap, NEW.base_amount), NEW.base_amount);
        IF NEW.discount_amount <> expected THEN
            RAISE EXCEPTION 'the benefit of a charge is the benefit of its award, limited to its cap and to the base'
                USING ERRCODE = 'check_violation';
        END IF;
    END IF;

    SELECT * INTO posting FROM ledger_transaction
        WHERE institution_id = NEW.institution_id AND id = NEW.ledger_transaction_id;
    IF NOT FOUND
            OR posting.kind <> 'CHARGE'
            OR posting.source_module <> 'charges'
            OR posting.source_ref_id IS DISTINCT FROM NEW.id
            OR posting.posting_xid <> pg_current_xact_id()::text::bigint
            OR (NEW.origin = 'AUTOMATIC' AND posting.effective_on <> NEW.period_start) THEN
        RAISE EXCEPTION 'a charge has the CHARGE transaction that this database transaction posted for it'
            USING ERRCODE = 'check_violation';
    END IF;
    SELECT count(*), COALESCE(sum(e.amount), 0), min(e.currency)
      INTO debit_count, debit_total, debit_ccy
      FROM ledger_entry e
      JOIN ledger_student_account sa ON sa.institution_id = e.institution_id AND sa.id = e.student_account_id
     WHERE e.institution_id = NEW.institution_id AND e.transaction_id = NEW.ledger_transaction_id
       AND e.side = 'DEBIT' AND sa.student_id = NEW.student_id;
    SELECT count(*), COALESCE(sum(amount), 0) INTO all_debits, all_total FROM ledger_entry
     WHERE institution_id = NEW.institution_id AND transaction_id = NEW.ledger_transaction_id AND side = 'DEBIT';
    IF NEW.total_amount > 0 THEN
        IF debit_count <> 1 OR debit_total <> NEW.total_amount OR debit_ccy <> NEW.total_currency THEN
            RAISE EXCEPTION 'the debit of the student sub-account of a charge is its total, in its currency'
                USING ERRCODE = 'check_violation';
        END IF;
    ELSIF debit_count <> 0 THEN
        RAISE EXCEPTION 'a charge with nothing to pay has no debit on the student sub-account'
            USING ERRCODE = 'check_violation';
    END IF;
    -- Every other debit is the benefit: one entry for its amount when there is a benefit, none when there is not.
    other_debits := all_debits - debit_count;
    IF NEW.discount_amount > 0 THEN
        expected_other := 1;
    ELSE
        expected_other := 0;
    END IF;
    IF other_debits <> expected_other OR all_total - debit_total <> NEW.discount_amount THEN
        RAISE EXCEPTION 'the only other debit of a charge is its benefit'
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END;
$$;

-- The void of a charge: the credit of the student sub-account is the total of the charge, and none when the total is zero.
CREATE OR REPLACE FUNCTION charges_charge_void_before_insert() RETURNS trigger
    LANGUAGE plpgsql
    SECURITY INVOKER
    SET search_path = pg_catalog, public
AS $$
DECLARE
    original      charges_charge%ROWTYPE;
    reversal      ledger_transaction%ROWTYPE;
    credit_count  integer;
    credit_total  numeric;
    credit_ccy    text;
BEGIN
    SELECT * INTO original FROM charges_charge
        WHERE institution_id = NEW.institution_id AND id = NEW.charge_id;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'a void names a charge of the institution' USING ERRCODE = 'check_violation';
    END IF;
    SELECT * INTO reversal FROM ledger_transaction
        WHERE institution_id = NEW.institution_id AND id = NEW.reversal_transaction_id;
    IF NOT FOUND
            OR reversal.kind <> 'REVERSAL'
            OR reversal.source_module <> 'charges'
            OR reversal.source_ref_id IS DISTINCT FROM original.id
            OR reversal.reverses_transaction_id IS DISTINCT FROM original.ledger_transaction_id
            OR reversal.posting_xid <> pg_current_xact_id()::text::bigint THEN
        RAISE EXCEPTION 'a void has the REVERSAL of the charge transaction that this database transaction posted for it'
            USING ERRCODE = 'check_violation';
    END IF;
    SELECT count(*), COALESCE(sum(e.amount), 0), min(e.currency)
      INTO credit_count, credit_total, credit_ccy
      FROM ledger_entry e
      JOIN ledger_student_account sa ON sa.institution_id = e.institution_id AND sa.id = e.student_account_id
     WHERE e.institution_id = NEW.institution_id AND e.transaction_id = NEW.reversal_transaction_id
       AND e.side = 'CREDIT' AND sa.student_id = original.student_id;
    IF original.total_amount > 0 THEN
        IF credit_count <> 1 OR credit_total <> original.total_amount OR credit_ccy <> original.total_currency THEN
            RAISE EXCEPTION 'the credit of the student sub-account of a void is the total of the charge, in its currency'
                USING ERRCODE = 'check_violation';
        END IF;
    ELSIF credit_count <> 0 THEN
        RAISE EXCEPTION 'the void of a charge with nothing to pay has no credit on the student sub-account'
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END;
$$;
